            <p class="text-justify">Primary care is delivered through TMO’s Primary Health Care directorate. On Rarotonga, outpatient care is provided at the Tupapa Primary Health Centre and through Puna community health clinics (puna are the traditional districts of Rarotonga). These sites provide in-person and telephone consultations, wound dressings, injections, minor operations and preventive clinics such as NCD clinics. In the Pa Enua, each inhabited island has a TMO health clinic, generally staffed by nurse practitioners and registered nurses; Pukapuka has a resident doctor. TMO’s 2025 facility chart also counts child welfare clinics and public dental clinics, which are the most widely distributed facility types, spread across Rarotonga, the Southern Group and the Northern Group.</p>
