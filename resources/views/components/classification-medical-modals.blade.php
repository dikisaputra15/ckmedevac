            <h6 class="fw-bold"><b>Overview</b></h6>
            <p class="text-justify">Aitutaki Hospital, in Araura village on Aitutaki, is the only hospital outside Rarotonga and the sole health provider for Aitutaki, the second most populous island. In 2025 it had two resident doctors and 10 nurses. Admissions nearly doubled from 125 in 2021 to 246 in 2025, and bed occupancy rose from 3.1% to 7.9% over the same period.</p>
            <p class="text-justify"><strong>Note:</strong> No law classifies Aitutaki Hospital separately. TMO’s Infection Prevention and Control Guidelines 2023 note that, “due to its size,” Aitutaki Hospital may combine committee functions. Record it as “Outer Island Hospital — public (TMO).” Aitutaki is also the largest source of domestic referrals to Rarotonga.</p>
            <h6 class="fw-bold"><b>Role</b></h6>
            <ul>
                <li>Provide primary care, emergency care and basic inpatient care for Aitutaki</li>
                <li>Refer patients to Rarotonga Hospital.</li>
            </ul>
            <h6 class="fw-bold"><b>Clinical Service</b></h6>
            <p><strong>Typical Bed Capacity</strong></p>
            <ul>
                <li>About 26 beds (secondary source: University of Otago, quoting a hospital doctor); not confirmed in official sources</li>
            </ul>
