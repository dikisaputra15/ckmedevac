            <h6 class="fw-bold"><b>Overview</b></h6>
            <p class="text-justify">Rarotonga Hospital, on the main island of Rarotonga, is the national referral hospital and the center of TMO’s Hospital Health Services directorate. TMO describes its services as public health, primary and secondary hospital services, supported by visiting specialist teams. Patients are referred from Pa Enua facilities to Rarotonga and, where necessary, onwards to overseas providers. More than 95% of births in the Cook Islands take place on Rarotonga, and Rarotonga Hospital is the main facility for childbirth.</p>
            <p class="text-justify"><strong>Note:</strong> TMO’s National Health Information Bulletin 2025 states that Rarotonga is “the only island with a hospital, primary care centre, private community clinic, private medical clinics, and pharmacies.” The same report, and TMO’s Infection Prevention and Control Guidelines 2023, also refer to Aitutaki Hospital, so the Bulletin’s facility chart appears to count Aitutaki among Pa Enua health facilities. Record Rarotonga Hospital as “National Referral Hospital — public (TMO), secondary care.”</p>
            <h6 class="fw-bold"><b>Role</b></h6>
            <ul>
                <li>Receive domestic referrals from all Pa Enua islands (554 domestic referrals in 2025, half of them from Aitutaki)</li>
                <li>Provide emergency, inpatient, outpatient, surgical, anesthetic and maternity care</li>
                <li>Initiate overseas referrals under the TMO Patient Referral Policy 2026.</li>
            </ul>
            <h6 class="fw-bold"><b>Clinical Service</b></h6>
            <p><strong>Typical Bed Capacity</strong></p>
            <ul>
                <li>The Cook Islands as a whole had 152 hospital beds in 2025 (8.8 per 1,000 population). Rarotonga Hospital accounts for most of them, but a facility-level count was not published in the sources reviewed. Average bed occupancy at Rarotonga was 15.6% in 2025</li>
            </ul>
            <p><em><strong>Note:</strong> Legal basis: Ministry of Health Act 2013, Sections 6(a), 8(2)(b) and 13. Role and statistics come from the TMO National Health Information Bulletin 2025.</em></p>
